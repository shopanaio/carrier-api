// Generates the typed models and the operation classes of the eCom API from contracts/ukrposhta-ecom.openapi.json.
//
//   node scripts/generate-contract.mjs            writes src/contract/generated/{types,operations}.ts
//   (run through `yarn generate`, which also formats the output with prettier)
//
// Operations that a hand-written service already implements (documented differently from the snapshot, or needing
// care) are skipped; every other operation of the snapshot becomes a method here.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(readFileSync(join(root, 'contracts/ukrposhta-ecom.openapi.json'), 'utf8'));
const servicesDir = join(root, 'src/contract/services');
const outTypes = join(root, 'src/contract/generated/types.ts');
const outOps = join(root, 'src/contract/generated/operations.ts');

// Enum values the documentation (09.03.2026 and later) lists and the snapshot lacks.
const ENUM_ADD = {
  ShipmentType: ['CARGO', 'VALUABLE_LETTER'],
  ShipmentGroupShipmentType: ['CARGO', 'VALUABLE_LETTER'],
  PackageType: ['EMS', 'PRIME'],
  OnFailReceiveType: ['RETURN_AFTER_5_DAYS'],
  LifecycleStatus: ['IN_DEPARTMENT', 'STORAGE', 'CANCELED', 'DELETED'],
  Status1: ['IN_DEPARTMENT', 'STORAGE', 'CANCELED', 'DELETED'],
};

const schemas = spec.components.schemas;
for (const [name, values] of Object.entries(ENUM_ADD))
  schemas[name].enum = [...new Set([...schemas[name].enum, ...values])];

// ---------- types ----------

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = name =>
  IDENT.test(name)
    ? name
    : JSON.stringify(name).replace(/[^\x20-\x7e]/g, c => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`);
const literal = value =>
  JSON.stringify(value).replace(/[^\x20-\x7e]/g, c => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`);
// The snapshot has Cyrillic look-alikes inside English descriptions ("\\u0421reate"); comments stay ASCII-only.
const LOOKALIKES = {
  '\u0410': 'A',
  '\u0412': 'B',
  '\u0421': 'C',
  '\u0415': 'E',
  '\u041d': 'H',
  '\u0406': 'I',
  '\u041a': 'K',
  '\u041c': 'M',
  '\u041e': 'O',
  '\u0420': 'P',
  '\u0422': 'T',
  '\u0425': 'X',
  '\u0430': 'a',
  '\u0441': 'c',
  '\u0435': 'e',
  '\u0456': 'i',
  '\u043e': 'o',
  '\u0440': 'p',
  '\u0445': 'x',
};
const ascii = text => text.replace(/[^\x00-\x7f]/g, c => LOOKALIKES[c] ?? '?');
const doc = (text, indent = '') => {
  const clean = ascii(text ?? '')
    .replace(/\s+/g, ' ')
    .replace(/\*\//g, '* /')
    .trim();
  return clean ? `${indent}/** ${clean} */\n` : '';
};

let refPrefix = '';

function render(schema, indent = '') {
  if (!schema || typeof schema !== 'object') return 'unknown';
  if (schema.$ref) return `${refPrefix}${schema.$ref.split('/').pop()}`;
  let type;
  if (schema.enum) type = schema.enum.map(literal).join(' | ');
  else if (schema.allOf) type = schema.allOf.map(s => render(s, indent)).join(' & ');
  else if (schema.oneOf || schema.anyOf) type = (schema.oneOf ?? schema.anyOf).map(s => render(s, indent)).join(' | ');
  else if (schema.type === 'array') type = `Array<${render(schema.items, indent)}>`;
  else if (schema.type === 'integer' || schema.type === 'number') type = 'number';
  else if (schema.type === 'boolean') type = 'boolean';
  else if (schema.type === 'string') type = 'string';
  else if (schema.type === 'object' || schema.properties || schema.additionalProperties)
    type = renderObject(schema, indent);
  else type = 'unknown';
  return schema.nullable && type !== 'unknown' ? `${type} | null` : type;
}

function renderObject(schema, indent) {
  const props = Object.entries(schema.properties ?? {});
  if (props.length === 0) {
    const extra = schema.additionalProperties;
    return extra && typeof extra === 'object' ? `Record<string, ${render(extra, indent)}>` : 'Record<string, unknown>';
  }
  const required = new Set(schema.required ?? []);
  const inner = `${indent}  `;
  const lines = props.map(([name, prop]) => {
    const optional = !required.has(name);
    const type = render(prop, inner);
    // The real API answers null for every unset field, so optional properties may be null.
    const nullable = optional && type !== 'unknown' && !/\| null$/.test(type) ? `${type} | null` : type;
    return `${doc(prop.description, inner)}${inner}${key(name)}${optional ? '?' : ''}: ${nullable};`;
  });
  return `{\n${lines.join('\n')}\n${indent}}`;
}

const typeLines = [
  '// AUTO-GENERATED by scripts/generate-contract.mjs from contracts/ukrposhta-ecom.openapi.json. Do not edit.',
  '',
];
for (const [name, schema] of Object.entries(schemas)) {
  const body = render(schema);
  typeLines.push(`${doc(schema.description)}export type ${name} = ${body};`, '');
}

// ---------- operations ----------

const norm = path => path.replace(/\{[^}]+\}/g, '{}');
const covered = new Set();
for (const file of readdirSync(servicesDir)) {
  if (!file.endsWith('.ts')) continue;
  const text = readFileSync(join(servicesDir, file), 'utf8');
  const lines = text.split('\n');
  for (const m of text.matchAll(/this\.remove\(\s*'([^']+)'/g)) covered.add(`DELETE ${norm(m[1])}`);
  // Built from a list of ids (`/barcodes/all-of/a&b`), so the template is not a literal.
  if (text.includes('/barcodes/all-of/')) covered.add('GET /barcodes/all-of/{}');
  lines.forEach((line, i) => {
    const m = /method: '(\w+)'/.exec(line);
    if (!m) return;
    const window = lines.slice(i, i + 8).join('\n');
    for (const p of window.matchAll(/['`](\/[^'`$]*(?:\$\{[^}]*\}[^'`]*)*)['`]/g)) covered.add(`${m[1]} ${norm(p[1])}`);
  });
}

const GROUP_RULES = [
  [/^\/(addresses)/, 'addresses'],
  [/^\/(clients|client-addresses|client-phones|client-emails|phones)/, 'clients'],
  [/^\/courier-service/, 'courier'],
  [/^\/(domestic\/delivery-price|international\/delivery-price)/, 'pricing'],
  [/^\/(dictionaries|banks)/, 'reference'],
  [/^\/barcodes/, 'barcodes'],
  [/^\/transfers/, 'transfers'],
  [/^\/(letters|domestic\/letters)/, 'letters'],
  [/^\/(countries|constraints-per-countries)/, 'countries'],
  [/^\/delivery-notifications/, 'deliveryNotifications'],
  [/^\/(document-back)/, 'documentBack'],
  [/document-back/, 'documentBack'],
  [/delivery-notification/, 'deliveryNotifications'],
  [/^\/shipment-groups/, 'shipmentGroups'],
  [/^\/shipments/, 'shipments'],
  [/^\/international/, 'international'],
];
const BINARY =
  /\/(sticker|label|form|form103a?|form119|ems|c6|cn07|cn22|cn23|cp71|cp95_cn29|dl|tfp3|forms|simple-statement|sticker-form119)$|\/international\/form\//;
const group = (path, binary) => {
  if (/^\/(letters|domestic\/letters)/.test(path)) return 'letters';
  if (binary) return 'labels';
  for (const [re, name] of GROUP_RULES) if (re.test(path)) return name;
  return 'misc';
};

// Names for operations whose operationId is not usable as a method name.
const NAME_OVERRIDES = {
  Findphoneprohibitionsbycountryusingget1: 'listPhoneProhibitionsByCountry',
  FindPhoneProhibitionsByCountryUsingGET: 'getPhoneProhibitionByCountry',
  getEMSFormUsingGETbySG: 'getShipmentGroupEmsForm',
  getEMSFormUsingGET: 'getEmsForm',
  getShipmentGroupStickerUsingGET_1: 'getShipmentGroupLabel',
  getShipmentGroupStickerUsingGET: 'getShipmentGroupForm',
  getShipmentGroupForm103AUsingGET: 'getShipmentGroupForm103',
  getShipmentStickerUsingGET: 'getShipmentForm',
  getFormCP95_CN29UsingGET: 'getFormCp95Cn29',
  Getallshipmentgroupsbyclientusingget1: 'listShipmentGroupsByClient',
  CalculateDeliveryPriceUsingPOST: 'calculateInternationalDeliveryPrice',
  Calculatedeliverypriceusingpost1: 'calculateLettersDeliveryPrice',
  Calculatedeliverypriceusingpost2: 'calculateDomesticDeliveryPrice',
};

const SKIP = new Set(['/doc', '/help', '/international-doc']);
const ops = [];
for (const [path, item] of Object.entries(spec.paths)) {
  if (SKIP.has(path)) continue;
  for (const [verb, op] of Object.entries(item)) {
    const method = verb.toUpperCase();
    if (!['GET', 'POST', 'PUT', 'DELETE', 'PATCH'].includes(method)) continue;
    if (covered.has(`${method} ${norm(path)}`)) continue;
    const params = op.parameters ?? [];
    const responseSchema =
      op.responses?.['200']?.content?.['*/*']?.schema ?? op.responses?.['200']?.content?.['application/json']?.schema;
    const json = path.includes('json') || path.includes('/sticker-json');
    const binary = !json && method === 'GET' && BINARY.test(path);
    ops.push({
      method,
      path,
      id: op.operationId,
      summary: op.summary ?? op.description ?? '',
      pathParams: params.filter(p => p.in === 'path'),
      queryParams: params.filter(p => p.in === 'query' && p.name !== 'token'),
      token: params.some(p => p.in === 'query' && p.name === 'token'),
      body: op.requestBody?.content?.['application/json']?.schema,
      bodyRequired: op.requestBody?.required,
      response: responseSchema,
      binary,
      group: group(path, binary),
    });
  }
}

const lowerFirst = s => s[0].toLowerCase() + s.slice(1);
const pascal = s => s.replace(/(^|[^A-Za-z0-9])([A-Za-z0-9])/g, (_, __, c) => c.toUpperCase());
function methodName(op) {
  if (NAME_OVERRIDES[op.id]) return NAME_OVERRIDES[op.id];
  const base = op.id.replace(/using(get|post|put|delete)\d*(_\d+)?$/i, '').replace(/_\d+$/, '');
  return lowerFirst(base.replace(/[^A-Za-z0-9]/g, ''));
}

refPrefix = 'T.';
const byGroup = new Map();
for (const op of ops) {
  const list = byGroup.get(op.group) ?? [];
  list.push(op);
  byGroup.set(op.group, list);
}

for (const name of [
  'addresses',
  'barcodes',
  'clients',
  'courier',
  'labels',
  'pricing',
  'shipmentGroups',
  'shipments',
]) {
  if (!byGroup.has(name)) byGroup.set(name, []);
}

const STANDALONE = new Set(['letters', 'deliveryNotifications', 'documentBack', 'countries', 'international', 'misc']);
const out = [
  '// AUTO-GENERATED by scripts/generate-contract.mjs from contracts/ukrposhta-ecom.openapi.json. Do not edit.',
  "import type { BinaryData } from '@shopana/carrier-core';",
  "import type { CallOptions } from '../types/common';",
  "import type { UkrposhtaContractContext } from '../services/base';",
  "import { WITHOUT_TOKEN, WITH_TOKEN } from '../services/base';",
  "import type * as T from './types';",
  '',
  '/** One generated operation, for documentation and tests. */',
  'export interface OperationInfo {',
  '  group: string;',
  '  method: string;',
  '  httpMethod: string;',
  '  path: string;',
  '  token: boolean;',
  '  binary: boolean;',
  '}',
  '',
];
const info = [];
for (const [groupName, list] of [...byGroup].sort(([a], [b]) => a.localeCompare(b))) {
  const className = `${pascal(groupName)}Operations`;
  const used = new Set();
  const methods = [];
  for (const op of list) {
    let name = methodName(op);
    if (used.has(name)) name = `${name}${pascal(op.method.toLowerCase())}`;
    if (used.has(name)) name = `${name}${used.size}`;
    used.add(name);
    const args = [];
    for (const p of op.pathParams) args.push(`${key(p.name)}: ${render(p.schema)}`);
    for (const p of op.queryParams)
      args.push(
        `${doc(p.description, '    ')}    ${key(p.name)}${p.required ? '' : '?'}: ${render(p.schema)};`.replace(
          /;$/,
          '',
        ),
      );
    const fields = [];
    for (const p of op.pathParams) fields.push(`${doc(p.description, '    ')}    ${key(p.name)}: ${render(p.schema)};`);
    for (const p of op.queryParams)
      fields.push(`${doc(p.description, '    ')}    ${key(p.name)}${p.required ? '' : '?'}: ${render(p.schema)};`);
    if (op.body) fields.push(`    body${op.bodyRequired ? '' : '?'}: ${render(op.body, '    ')};`);
    const argsType = fields.length ? `{\n${fields.join('\n')}\n  }` : null;
    const resType = op.binary ? 'BinaryData' : op.response ? render(op.response, '  ') : 'unknown';
    const pathExpr = op.pathParams.length
      ? `,\n      pathParams: { ${op.pathParams.map(p => `${key(p.name)}: args.${p.name}`).join(', ')} }`
      : '';
    const queryExpr = op.queryParams.length
      ? `,\n      query: { ${op.queryParams.map(p => `${key(p.name)}: args.${p.name}`).join(', ')} }`
      : '';
    const bodyExpr = op.body ? ',\n      json: args.body' : '';
    const client = op.binary ? 'this.ctx.forms' : 'this.ctx.http';
    const sig = argsType ? `args: ${argsType}, options: CallOptions = {}` : 'options: CallOptions = {}';
    methods.push(
      `${doc(`${op.method} ${op.path}${op.summary ? ` - ${op.summary}` : ''}`, '  ')}  ${name}(${sig}): Promise<${resType}> {\n    return ${client}.request<${resType}>({\n      method: '${op.method}',\n      path: '${op.path}'${pathExpr}${queryExpr}${bodyExpr}${op.binary ? ",\n      responseType: 'binary'" : ''},\n      meta: ${op.token ? 'WITH_TOKEN' : 'WITHOUT_TOKEN'},\n      signal: options.signal,\n    });\n  }`,
    );
    info.push({
      group: groupName,
      method: name,
      httpMethod: op.method,
      path: op.path,
      token: op.token,
      binary: op.binary,
    });
  }
  const standalone = STANDALONE.has(groupName);
  out.push(
    `/** Operations of the "${groupName}" group that no hand-written method covers. */`,
    `export class ${className} {`,
    ...(standalone ? [`  readonly namespace = '${groupName}' as const;`] : []),
    '  protected ctx!: UkrposhtaContractContext;',
    '',
    '  attach(ctx: UkrposhtaContractContext) {',
    '    this.ctx = ctx;',
    '  }',
    '',
    methods.join('\n\n'),
    '}',
    '',
  );
}
out.push(
  '/** Every generated operation. */',
  `export const GENERATED_OPERATIONS: OperationInfo[] = ${JSON.stringify(info, null, 2)};`,
  '',
);

const typesText = typeLines.join('\n');
writeFileSync(outTypes, typesText);
writeFileSync(outOps, out.join('\n'));
console.log(`${ops.length} operations, ${Object.keys(schemas).length} schemas`);
